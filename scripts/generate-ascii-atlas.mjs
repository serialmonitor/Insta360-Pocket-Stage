// Render a character into the pixel buffer
function renderChar(pixels, charCode, cellX, cellY) {
  const fontData = FONT_5X7[charCode] || FONT_5X7[32]
  const scale = 4 // 5*4=20px wide, 7*4=28px tall, centered in 32x32
  const offsetX = cellX + Math.floor((CELL_SIZE - 5 * scale) / 2)
  const offsetY = cellY + Math.floor((CELL_SIZE - 7 * scale) / 2)

  for (let col = 0; col < 5; col++) {
    const colBits = fontData[col]
    for (let row = 0; row < 7; row++) {
      if (colBits & (1 << row)) {
        // Fill scaled pixel block
        for (let sx = 0; sx < scale; sx++) {
          for (let sy = 0; sy < scale; sy++) {
            const px = offsetX + col * scale + sx
            const py = offsetY + row * scale + sy
            if (px >= 0 && px < WIDTH && py >= 0 && py < HEIGHT) {
              const idx = (py * WIDTH + px) * 4
              pixels[idx] = 255     // R
              pixels[idx + 1] = 255 // G
              pixels[idx + 2] = 255 // B
              pixels[idx + 3] = 255 // A
            }
          }
        }
      }
    }
  }
}

// Minimal PNG encoder
function encodePNG(width, height, pixels) {
  // PNG signature
  const signature = Buffer.from([137, 80, 78, 71, 13, 10, 26, 10])

  // IHDR chunk
  const ihdr = Buffer.alloc(13)
  ihdr.writeUInt32BE(width, 0)
  ihdr.writeUInt32BE(height, 4)
  ihdr[8] = 8  // bit depth
  ihdr[9] = 6  // color type: RGBA
  ihdr[10] = 0 // compression
  ihdr[11] = 0 // filter
  ihdr[12] = 0 // interlace
  const ihdrChunk = makeChunk('IHDR', ihdr)

  // IDAT chunk (raw pixel data with filter bytes)
  const rawData = Buffer.alloc(height * (1 + width * 4))
  for (let y = 0; y < height; y++) {
    rawData[y * (1 + width * 4)] = 0 // filter: None
    for (let x = 0; x < width * 4; x++) {
      rawData[y * (1 + width * 4) + 1 + x] = pixels[y * width * 4 + x]
    }
  }
  const compressed = deflateSync(rawData)
  const idatChunk = makeChunk('IDAT', compressed)

  // IEND chunk
  const iendChunk = makeChunk('IEND', Buffer.alloc(0))

  return Buffer.concat([signature, ihdrChunk, idatChunk, iendChunk])
}

function makeChunk(type, data) {
  const len = Buffer.alloc(4)
  len.writeUInt32BE(data.length, 0)
  const typeB = Buffer.from(type, 'ascii')
  const crcData = Buffer.concat([typeB, data])
  const crc = Buffer.alloc(4)
  crc.writeUInt32BE(crc32(crcData), 0)
  return Buffer.concat([len, typeB, data, crc])
}

function crc32(buf) {
  let crc = 0xFFFFFFFF
  for (let i = 0; i < buf.length; i++) {
    crc ^= buf[i]
    for (let j = 0; j < 8; j++) {
      if (crc & 1) {
        crc = (crc >>> 1) ^ 0xEDB88320
      } else {
        crc = crc >>> 1
      }
    }
  }
  return (crc ^ 0xFFFFFFFF) >>> 0
}

// ─── Main ────────────────────────────────────────────────────────────────────

function generate() {
  // Create RGBA pixel buffer (black background)
  const pixels = Buffer.alloc(WIDTH * HEIGHT * 4, 0)
  // Set alpha to 255 for all pixels (opaque black)
  for (let i = 3; i < pixels.length; i += 4) {
    pixels[i] = 255
  }

  // Render each character into its grid cell
  for (let i = 0; i < GRID_COLS * GRID_ROWS; i++) {
    const col = i % GRID_COLS
    const row = Math.floor(i / GRID_COLS)
    const char = CHARS[i] || ' '
    const charCode = char.charCodeAt(0)
    renderChar(pixels, charCode, col * CELL_SIZE, row * CELL_SIZE)
  }

  // Encode as PNG
  const png = encodePNG(WIDTH, HEIGHT, pixels)

  // Write output
  const outDir = resolve(ROOT, 'public/assets')
  if (!existsSync(outDir)) {
    mkdirSync(outDir, { recursive: true })
  }
  const outPath = resolve(outDir, 'ascii-atlas.png')
  writeFileSync(outPath, png)

  console.log(`✅ ASCII atlas generated: ${outPath}`)
  console.log(`   Grid: ${GRID_COLS}x${GRID_ROWS}, Cell: ${CELL_SIZE}px, Total: ${WIDTH}x${HEIGHT}`)
  console.log(`   Characters: 95 printable ASCII (0x20-0x7E), sorted by brightness`)
  console.log(`   Pure JS PNG encoder — no native dependencies required`)
}

generate()
